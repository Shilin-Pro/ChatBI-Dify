-- ------------------------------------------------------------
-- 4. 订单
-- ------------------------------------------------------------
CREATE TABLE orders (
    id            INT PRIMARY KEY AUTO_INCREMENT COMMENT '订单ID',
    order_no      VARCHAR(32) NOT NULL UNIQUE COMMENT '订单号',
    customer_id   INT NOT NULL COMMENT '客户ID',
    order_date    DATE NOT NULL COMMENT '下单日期',
    total_amount  DECIMAL(12,2) NOT NULL COMMENT '订单总额',
    discount      DECIMAL(10,2) DEFAULT 0 COMMENT '优惠金额',
    pay_amount    DECIMAL(12,2) NOT NULL COMMENT '实付金额',
    status        VARCHAR(20) NOT NULL COMMENT '状态:待付款/已付款/已发货/已完成/已取消/已退款',
    pay_method    VARCHAR(20) COMMENT '支付方式:微信/支付宝/银行卡',
    province      VARCHAR(20) COMMENT '收货省份',
    city          VARCHAR(30) COMMENT '收货城市',
    created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_customer (customer_id),
    INDEX idx_date (order_date),
    INDEX idx_status (status),
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单表';

